/** Where the generated catalogue lives, relative to the project root. */
export const CATALOGUE_FILE = 'src/content/catalogue.generated.ts';

/**
 * The text of `catalogue.generated.ts`: the ids of the playable topics and their levels, of the stages that have case
 * studies, and the default course. It
 * exists so that the root layout (the service worker's route list, the profile creation) can know what exists
 * without importing a single pack or generator. Written by `npm run catalogue` (scripts/generate-catalogue.ts), which
 * runs before every build and test run; a unit test fails when the committed file is out of date.
 */
export function renderCatalogue(): string {
  const topics = PACKS.map((p) => ({ id: p.topicId, levelIds: [...p.levels].sort((a, b) => a.order - b.order).map((l) => l.id) }));
  return [
    '// GENERATED by `npm run catalogue` (scripts/generate-catalogue.ts) from the topic packs. Do not edit by hand.',
    '// Ids only, so that the root layout can know what exists without importing any pack or generator.',
    '',
    `export const COURSE_IDS: readonly string[] = ${JSON.stringify(COURSES.map((c) => c.id))};`,
    '',
    '/** The course a new learner joins: the first one. */',
    `export const DEFAULT_COURSE_ID = ${JSON.stringify(COURSES[0].id)};`,
    '',
    '/** Every topic of each course in course order, playable or not: this says which course a topic belongs to. */',
    `export const COURSE_TOPIC_IDS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(Object.fromEntries(COURSES.map((c) => [c.id, c.topics.map((t) => t.id)])))};`,
    '',
    '/** The playable topics in course order, each with the ids of its levels in level order. */',
    'export const CATALOGUE_TOPICS: readonly { readonly id: string; readonly levelIds: readonly string[] }[] = ' +
      JSON.stringify(topics, null, 2) +
      ';',
    '',
    '/** The stages that have case studies (each has a page under /cases/play), in the order a student meets them. */',
    `export const CATALOGUE_CASE_STAGES: readonly string[] = ${JSON.stringify(CASE_STAGES.filter((s) => s.cases.length > 0).map((s) => s.id))};`,
    '',
  ].join('\n');
}

/** Where the generated outline lives, relative to the project root. */
export const OUTLINE_FILE = 'src/content/outline.generated.ts';

/** A list as source text, one row to a line, so that a change to the content shows as the lines that changed. */
const rows = (list: readonly unknown[], indent: string): string =>
  list.length === 0 ? '[]' : `[\n${list.map((row) => `${indent}  ${JSON.stringify(row)},`).join('\n')}\n${indent}]`;

/**
 * The text of `outline.generated.ts`: what the screens that list things need of every pack, template and case study,
 * so that they import no pack and no generator. Written by `npm run catalogue` with the catalogue, and checked by a
 * unit test in the same way.
 */
export function renderOutline(): string {
  const { topics, stages } = outlineOf(PACKS, TEMPLATES, CASE_STAGES);
  return [
    '// GENERATED by `npm run catalogue` (scripts/generate-catalogue.ts) from the topic packs and the generators. Do not edit by hand.',
    '// What the screens that list things need, so that they import no pack and no generator. Read through outline.ts.',
    "import type { OutlineData } from './outline';",
    '',
    'export const OUTLINE: OutlineData = {',
    '  topics: [',
    ...topics.flatMap((t) => [
      '    {',
      `      id: ${JSON.stringify(t.id)},`,
      `      concepts: ${rows(t.concepts, '      ')},`,
      `      cards: ${rows(t.cards, '      ')},`,
      `      questions: ${rows(t.questions, '      ')},`,
      `      templates: ${rows(t.templates, '      ')},`,
      `      levels: ${rows(t.levels, '      ')},`,
      '    },',
    ]),
    '  ],',
    '  stages: [',
    ...stages.flatMap(({ cases, ...stage }) => ['    {', ...Object.entries(stage).map(([key, value]) => `      ${key}: ${JSON.stringify(value)},`), `      cases: ${rows(cases, '      ')},`, '    },']),
    '  ],',
    '};',
    '',
  ].join('\n');
}

/** Where the generated card titles live, relative to the project root. */
export const CARD_TITLES_FILE = 'src/content/cardTitles.generated.ts';

/**
 * The text of `cardTitles.generated.ts`: the question on the front of every rule card, by card id, so that "Go to"
 * (Ctrl K) finds a card by what it asks without loading its topic. "Go to" fetches it the first time it opens; no
 * page loads it by itself. Written by `npm run catalogue` with the catalogue, and checked by a unit test in the same way.
 */
export function renderCardTitles(): string {
  const cards = PACKS.flatMap((p) => p.cards.map((c) => [c.id, c.prompt] as const));
  return [
    '// GENERATED by `npm run catalogue` (scripts/generate-catalogue.ts) from the topic packs. Do not edit by hand.',
    '// The front of every rule card, by card id: what "Go to" (Ctrl K) finds a card by. Loaded when "Go to" first opens.',
    '',
    'export const CARD_TITLES: Readonly<Record<string, string>> = {',
    ...cards.map(([id, prompt]) => `  ${JSON.stringify(id)}: ${JSON.stringify(prompt)},`),
    '};',
    '',
  ].join('\n');
}

/** Where the samples of the patterns live, relative to the project root. */
export const SAMPLES_FILE = 'src/content/samples.generated.ts';

/** The seed every sample is made from. */
export const SAMPLE_SEED = 1;
/** The longest a sample is, in characters, before it is cut at a word and ends with "…". */
export const SAMPLE_LENGTH = 110;

/** The first line of a text with its spaces closed up, cut at a word to at most `SAMPLE_LENGTH` characters. */
export function sampleLine(text: string): string {
  const line = (text.split('\n').find((l) => l.trim() !== '') ?? '').replace(/\s+/g, ' ').trim();
  if (line.length <= SAMPLE_LENGTH) return line;
  const cut = line.slice(0, SAMPLE_LENGTH - 1);
  const at = cut.lastIndexOf(' ');
  return `${(at > SAMPLE_LENGTH / 2 ? cut.slice(0, at) : cut).replace(/[\s,;:.]+$/, '')}…`;
}

/**
 * The text of `samples.generated.ts`: for every template the first line of the question it makes from `SAMPLE_SEED`,
 * and for every case study the first line of its case text. The Playground and the Case studies screen show it on
 * the card of a pattern, and import it only when they are opened: no other screen carries it, and no topic has to be
 * loaded to show it. Written by `npm run catalogue` with the catalogue, and checked by a unit test in the same way.
 */
export function renderSamples(): string {
  const samples = [
    ...TEMPLATES.map((t) => [t.id, sampleLine(generateFrom(t, SAMPLE_SEED).prompt)] as const),
    ...CASES.map((c) => [c.id, sampleLine(generateCase(c, SAMPLE_SEED)[0]?.context ?? '')] as const),
  ];
  return [
    '// GENERATED by `npm run catalogue` (scripts/generate-catalogue.ts) from the generators. Do not edit by hand.',
    '// A sample line of every pattern, by id, for the cards of the Playground and the Case studies screen; imported only there.',
    '',
    'export const SAMPLES: Readonly<Record<string, string>> = {',
    ...samples.map(([id, sample]) => `  ${JSON.stringify(id)}: ${JSON.stringify(sample)},`),
    '};',
    '',
  ].join('\n');
}

/** Where the figures of the landing page live, relative to the project root. */
export const LANDING_FILE = 'src/content/landing.generated.ts';

/**
 * The text of `landing.generated.ts`: what the landing page (`/`) says there is, counted from the packs, the
 * generators, the written answers and the viva banks, and the topics of each class by title, so that the page imports
 * no outline, catalogue or pack and its figures can never fall behind the content. Written by `npm run catalogue` with
 * the catalogue, and checked by a unit test in the same way.
 */
export function renderLanding(): string {
  const written: Record<string, number> = { 'cbse-11-accountancy': WRITTEN_11.length, 'cbse-12-accountancy': WRITTEN_12.length };
  const viva: Record<string, number> = { 'cbse-11-accountancy': VIVA_11.length, 'cbse-12-accountancy': VIVA_12.length };
  const courses = COURSES.map((course) => {
    const ids = new Set(course.topics.map((t) => t.id));
    const packs = PACKS.filter((p) => ids.has(p.topicId));
    const playable = new Set(packs.map((p) => p.topicId));
    return {
      id: course.id,
      label: /Class \d+/.exec(course.title)?.[0] ?? course.title,
      topics: course.topics
        .filter((t) => playable.has(t.id))
        .map((t) => ({ id: t.id, title: t.title, unit: t.unit, ...(partBOfTopic(t.id) ? { option: partBOfTopic(t.id) } : {}) })),
      counts: {
        topics: playable.size,
        lessons: packs.reduce((n, p) => n + p.levels.filter((l) => l.type === 'concept').length, 0),
        cards: packs.reduce((n, p) => n + p.cards.length, 0),
        questions: packs.reduce((n, p) => n + p.questions.length, 0),
        patterns: TEMPLATES.filter((t) => playable.has(t.topicId)).length,
        cases: CASES.filter((c) => playable.has(c.topicId)).length,
        assertionReason: packs.filter((p) => p.levels.some((l) => l.id.endsWith('-assertion-reason'))).length,
        written: written[course.id] ?? 0,
        viva: viva[course.id] ?? 0,
      },
    };
  });
  const sum = (key: keyof (typeof courses)[number]['counts']) => courses.reduce((n, c) => n + c.counts[key], 0);
  const totals = {
    topics: sum('topics'),
    lessons: sum('lessons'),
    cards: sum('cards'),
    questions: sum('questions'),
    patterns: sum('patterns'),
    cases: sum('cases'),
    assertionReason: sum('assertionReason'),
    written: sum('written'),
    viva: sum('viva'),
    paperKinds: PAPER_KINDS.length,
  };
  const full = { marks: BLUEPRINTS.full.marks, minutes: BLUEPRINTS.full.minutes, questions: questionCount(BLUEPRINTS.full) };
  return [
    '// GENERATED by `npm run catalogue` (scripts/generate-catalogue.ts) from the packs, generators, written answers and viva banks. Do not edit by hand.',
    '// What the landing page (/) counts and lists, so that it imports no outline, catalogue or pack.',
    '',
    'export interface LandingTopic {',
    '  readonly id: string;',
    '  readonly title: string;',
    '  readonly unit: string;',
    '  /** The Part B of Class 12 the topic belongs to, for a topic of one of the two choices. */',
    "  readonly option?: 'analysis' | 'computerised';",
    '}',
    '',
    'export interface LandingCounts {',
    '  readonly topics: number;',
    '  readonly lessons: number;',
    '  readonly cards: number;',
    '  /** Set questions, written once. */',
    '  readonly questions: number;',
    '  /** Question types: each makes a new question, with new figures, every time it is played. */',
    '  readonly patterns: number;',
    '  readonly cases: number;',
    '  /** Topics with a level of Assertion-Reason questions. */',
    '  readonly assertionReason: number;',
    '  readonly written: number;',
    '  readonly viva: number;',
    '}',
    '',
    '/** The playable courses, each with its playable topics in course order. */',
    `export const LANDING_COURSES: readonly { readonly id: string; readonly label: string; readonly topics: readonly LandingTopic[]; readonly counts: LandingCounts }[] = ${JSON.stringify(courses, null, 2)};`,
    '',
    '/** Both courses together; `paperKinds` is the kinds of mock paper (full, half-yearly, topic test). */',
    `export const LANDING_TOTALS: LandingCounts & { readonly paperKinds: number } = ${JSON.stringify(totals, null, 2)};`,
    '',
    '/** The full mock paper, in the CBSE pattern. */',
    `export const LANDING_FULL_PAPER: { readonly marks: number; readonly minutes: number; readonly questions: number } = ${JSON.stringify(full)};`,
    '',
  ].join('\n');
}
