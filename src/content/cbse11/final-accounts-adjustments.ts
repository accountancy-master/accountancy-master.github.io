const qid = (n: number) => `faa-q-${String(n).padStart(3, '0')}`;

/** A multiple-choice question; `options` are [text, why] pairs (why only for wrong ones) and `correct` is the index. */
const mcq = (
  n: number,
  conceptId: string,
  difficulty: Difficulty,
  prompt: string,
  options: [string, string?][],
  correct: number,
  explanation: string,
  hints: string[] = ['Think about which year the amount belongs to.', 'Is the balance something the business owns or owes?'],
): McqQuestion => ({
  id: qid(n), topicId: T, conceptId, difficulty, type: 'mcq', prompt, hints, explanation,
  options: options.map(([text, why], i) => ({ id: 'abcd'[i], text, ...(i === correct || !why ? {} : { why }) })),
  correct: 'abcd'[correct],
});

const tf = (n: number, conceptId: string, difficulty: Difficulty, prompt: string, correct: boolean, explanation: string): TrueFalseQuestion => ({
  id: qid(n), topicId: T, conceptId, difficulty, type: 'true_false', prompt, correct, explanation,
  hints: ['Decide what the adjustment does to profit and to the balance sheet.', 'Test the statement with a small example.'],
});

