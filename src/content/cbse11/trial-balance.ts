const qid = (n: number) => `tb-q-${String(n).padStart(3, '0')}`;

/** A multiple-choice question: the right answer goes at position `at`; each wrong option carries its mistake. */
function mcq(
  n: number,
  conceptId: string,
  difficulty: Difficulty,
  prompt: string,
  right: string,
  wrong: [string, string][],
  at: number,
  explanation: string,
  hints: [string, string],
): McqQuestion {
  const entries: { text: string; why?: string }[] = wrong.map(([text, why]) => ({ text, why }));
  entries.splice(at, 0, { text: right });
  const options = entries.map((e, i) => ({ id: 'abcd'[i], text: e.text, ...(e.why ? { why: e.why } : {}) }));
  return {
    id: qid(n), topicId: T, conceptId, difficulty, type: 'mcq', prompt, options,
    correct: 'abcd'[at], explanation, hints,
  };
}

